// ================================================
// Симптом: в режиме обучения перевод на русском начинает звучать и
// обрывается на середине — песня-сегмент стартует раньше конца фразы.
//
// Корневая причина: НЕВЕРНАЯ СЕМАНТИКА ТАЙМАУТА play(). В just_audio Future
// метода play() завершается НЕ при старте воспроизведения, а когда оно
// ЗАКОНЧИЛОСЬ или поставлено на паузу. Фикс v5.8.1 («защита от зависания
// после звонка») повесил на play() таймаут 1с и трактовал его как СБОЙ →
// _onPlaybackDone() → _player.stop(). Для фразы длиной 4–9с таймаут
// срабатывал ВСЕГДА → каждая фраза обрезалась через ~1 секунду.
//
// Исправление (offline_tts_engine.dart):
//   • таймаут play() теперь ПРОГЛАТЫВАЕТСЯ (TimeoutException пойман локально,
//     плеер не трогается) — «фраза ещё говорит» это норма, а не ошибка;
//   • завершение речи приходит как и раньше через playerStateStream →
//     _onPlaybackDone (ProcessingState.completed);
//   • истинный завис play() ловит study-watchdog (streak-политика v5.8.1:
//     максимум одна потерянная строка, TTS для песни не отключается);
//   • таймаут setFilePath (3с) ОСТАЁТСЯ ошибкой — он резолвится за
//     миллисекунды на локальном WAV, срабатывание означает реальный завис;
//   • реактивация аудиосессии setActive(true) перед воспроизведением
//     (фикс звонка v5.8.1) сохранена без изменений.


