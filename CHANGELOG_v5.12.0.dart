// Новая кнопка «A–B» справа от кнопки режимов повтора:
//   • тап 1 — точка A (начало отрезка, LIVE player.position —
//     wall-clock, не кэш positionStream, чтобы точка ложилась туда,
//     что слышит ухо);
//   • тап 2 — точка B (конец): отрезок A..B играет по кругу;
//   • тап 3 — сброс; долгое нажатие — сброс из любого состояния.
// Каждое действие подтверждается SnackBar'ом со временем точки
// («Начало отрезка A: 0:12», «Повтор отрезка включён: 0:12 – 0:25»).
//
// lib/services/ab_repeat_controller.dart (новый):
//   • чистая логика без плеера — конечный автомат
//     idle → startMarked → active → idle и решение shouldLoopBack;
//   • тап-B раньше A не ошибка: точка A переезжает на новую позицию;
//   • минимальная длина отрезка 1 с (короче — tooShort, A остаётся);
//   • unit-тесты: test/ab_repeat_controller_test.dart (15 кейсов —
//     фазы, границы, слишком короткий отрезок, сброс, уведомления).
//
// lib/services/audio_service.dart:
//   • владеет AbRepeatController'ом; enforcement цикла — в отдельном
//     ЧАСТОМ потоке позиций (createPositionStream maxPeriod 80 мс
//     против ~200 мс у штатного positionStream): перелёт за точку B
//     на каждом круге ≤ 80 мс — на слух незаметно;
//   • прыжок назад — сырой _player.seek(A): позиция уведомления
//     синхронизируется подпиской handler'а, без двойного seek'а;
//   • окно 400 мс после ЯВНОГО seek'а (слайдер/replay-10/forward-10)
//     цикл не срабатывает — иначе он боролся бы с перетаскиванием
//     ползунка за точку B (guard _lastExplicitSeekAt в seek/
//     seekToPosition);
//   • сброс при loadAudio (смена песни) — точки привязаны к песне;
//     работает и в фоне: enforcement живёт в AudioService, а не в UI.
//
// lib/widgets/ab_repeat_slider_track.dart (новый):
//   • трекшейп слайдера позиции: поверх штатной отрисовки Material
//     рисует полосу отрезка A..B (заливка + рамка + тонкие метки
//     краёв); пока выставлена только A — метка начала будущего
//     отрезка. Геометрия из getPreferredRect — совпадает с дорожкой
//     пиксель в пиксель при любой теме/плотности.
//
// lib/screens/player_screen.dart:
//   • кнопка _buildAbRepeatButton в ряду управления (buttonCount
//     7 → 8, стиль повторяет кнопку loop: активное состояние —
//     primaryContainer + рамка);
//   • слайдер позиции обёрнут SliderTheme с AbRepeatSliderTrackShape;
//   • при старте study-режима (кнопка/автостарт/рестарт) повторитель
