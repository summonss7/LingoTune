// ⏱ Автопроверка — раз в час вместо раз в сутки
// ================================================
// UpdateService.autoCheckInterval: 24 h → 1 h. Ожидание Артёма —
// «захожу в программу — она пишет»: с суточным окном релиз,
// опубликованный через час после прошлого запуска, молчал до
// следующих суток. Один GET крошечного манифеста в час — бесплатно
// даже для семейного сервера.
//
// 🔁 Сбой источника больше не «сжигает» проверку
// ================================================
// UpdateFlow.maybeAutoCheck: метка lastUpdateCheckMs ставилась ДО
// проверки — временный сбой сервера означал молчание на сутки.
// Теперь метка ставится только когда источник ОТВЕТИЛ
// (updateAvailable/upToDate); при sourceUnavailable/исключении —
// повтор при следующем запуске приложения.
