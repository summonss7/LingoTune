// ================================================
// Запрос: «задать время задержки или опережения озвучивания перевода —
// чтоб говорило раньше или позже, чем стоит временная метка».
//
// Раньше такой настройки НЕ было: существующая «Задержка синхронизации
// текста» (lyricsPositionOffset, 0–1 с) влияет только на подсветку строк —
// StudyModeService её не читал, TTS запускался строго по меткам LRC.
//
// Что добавлено:
//   • В диалоге настроек режима изучения (долгое нажатие на кнопку режима)
//     — слайдер «Смещение озвучки»: −5.0…+5.0 с, шаг 0.1.
//     Минус — говорить РАНЬШЕ метки (опережение), плюс — ПОЗЖЕ (задержка).
//     Под слайдером — пояснение.
//   • Действует в режиме «Поверх» (overlay): граница строки для триггера
//     речи ищется по смещённой позиции pos − offset (и в опросе позиции
//     каждые 150 мс, и при первичном определении строки). Точность —
//     интервал опроса 150 мс.
//   • Сегментные режимы («сначала перевод» / «сначала оригинал»)
//     последовательны по построению — смещение там не применяется
//     (отражено в подсказке UI).
//   • Хранение по образцу скорости речи: глобально `studyModeTtsOffset` +
//     пер-песенное `song_{id}_ttsOffset` (наследование глобального значения
//     при первом включении «Свои настройки для этой песни»), клэмп ±5 с.
//   • Локализация: 2 новых ключа (studyModeTtsOffset, studyModeTtsOffsetHint)
//     во всех 11 языках (ARB + абстрактный класс + реализации).


