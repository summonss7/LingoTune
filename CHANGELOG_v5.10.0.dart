// 📊 ФИЧА 1: ЭКВАЛАЙЗЕР ОТ НАСТОЯЩЕГО ЗВУКА
// ================================================
// Прежний эквалайзер (v5.9.0) был «псевдо»: столбики — суммы
// синусоид, никак не связанные с музыкой. Теперь он танцует от
// реального спектра играющего трека: ритм, такт, громкость.
//
// android/.../AudioVisualizerPlugin.kt (новый нативный плагин):
//   • android.media.audiofx.Visualizer на сессии 0 (глобальный
//     выходной микс): системный FFT того, что сейчас играет —
//     без декодирования файла и без вмешательства в аудиотракт;
//   • captureSize = max(диапазона).coerceAtMost(1024), rate ≤ 20 Гц;
//   • FFT (signed byte, пары re/im) → 32 логарифмические полосы
//     (низы широкие, верхы плотные — как слышит ухо), в полосе
//     среднее×0.6 + пик×0.4 (среднее глушит шум, пик ловит бочку),
//     нормировка /120 с гаммой 0.65 → байты 0..255;
//   • бины выше 70% спектра отброшены (выше ~16 кГц музыки нет,
//     шипение зря тянуло столбики вверх);
//   • MethodChannel lingotune/audio_visualizer (start/stop) +
//     EventChannel .../events (кадры); колбэк binder-потока →
//     mainHandler.post в sink;
//   • зарегистрирован в MainActivity (поле audioVisualizerPlugin,
//     как остальные нативные плагины);
//   • ограничения: нужно RECORD_AUDIO (уже объявлено для car
//     detection, runtime-запрос — на Dart-стороне); на части ROM
//     (de-Googled) конструктор Visualizer кидает → ошибка в Dart,
//     включается прежняя синусоидная заглушка.
//
// lib/services/audio_visualizer_service.dart (новый, синглтон):
//   • start(): Permission.microphone.request() → native 'start' →
//     подписка на broadcast-стрим; false при любом отказе;
//   • barStream: Stream<Uint8List> (32 байта 0..255 на кадр);
//   • stop(): cancel подписки + native 'stop' (release Visualizer —
//     экономия батареи, когда эквалайзер не виден).
//
// lib/utils/audio_band_processor.dart (новый, чистый Dart):
//   • атака мгновенная / спад экспоненциальный (tau 160 мс) — удар
//     бочки виден сразу, без дрожания между кадрами захвата;
//   • адаптивный гейн: нормировка на скользящий пик композиции
//     (спад ~3 с), гейн (0.9/peak).clamp(1, 3) — тихая запись не
//     «пол», громкая не «потолок»;
//   • бит: энергия нижней четверти полос (~бас/бочка) против
//     скользящего среднего ~2 с; скачок ×1.35 + рефрактерные 220 мс
//     → beat=1, экспоненциальное затухание (tau 120 мс);
//   • пик-шапки: максимум полосы, сползают 0.55/с;
//   • гамма 0.8 при нормировке байта — тихие полосы читаемы.
//
// lib/widgets/audio_equalizer_widget.dart (переписан):
//   • два режима: _SpectrumPainter (реальный спектр) и прежний
//     _EqualizerPainter (фолбэк-синусоиды);
//   • спектр: зеркальные столбики по центру, линейный ресемпл
//     32 полос → ширина экрана, цвет primary → transcriptAccent
//     («Аметист») / tertiary (другие темы);
//   • бит: радиальное свечение за столбиками (alpha 0.16×beat) +
//     столбики чуть выше (1+0.16×beat) + alpha 0.86+0.14×beat —
//     картинка «дышит» в такт;
//   • пик-шапки сверху и снизу зеркального столбика;
//   • в FFT-режиме AnimationController крутится всегда (спад/шапки/
//     бит живут в tick), заглушка — только пока player.playing;
//   • dispose(): stop() нативного захвата.


