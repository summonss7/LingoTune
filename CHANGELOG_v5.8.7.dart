// 🐛 ФИКС №1: ВЫКЛЮЧЕНИЕ ГОЛОСОВОГО РЕЖИМА ГЛУШИЛО ПЕСНЮ
// ================================================
// Симптом (режим «Поверх»): песня играет непрерывно, нажимаю верхнюю кнопку
// выключить голосовое — песня ставится на паузу.
//
// Причина: StudyModeService.stop() безусловно паузит плеер, а
// _toggleStudyMode после остановки ничего не возобновлял. Поведение не новое
// (существовало до v5.8.6), но противоречит новой философии разделения
// кнопок: кнопка режима управляет только голосовым слоем, транспорт —
// только play/pause.
//
// Исправление (player_screen.dart, _toggleStudyMode):
//   • Перед stop() захватывается wasAudible: сессия НЕ на пользовательской
//     паузе И (звучит озвучка isSpeaking ИЛИ player.playing ИЛИ
//     wasPlayingRecently — окно 2 мин покрывает kick-фазу).
//   • После await stop(): при wasAudible → ensurePlaybackAdvancing() —
//     продолжает обычное воспроизведение с текущей позиции, сам реактивирует
//     аудиосессию после TTS-хендоффа, лечит зомби just_audio, no-op если всё
//     здорово, не дёргает плеер при completed.
//   • stop() в сервисе не трогаем: остальные вызовы (смена песни, конец
//     песни, ошибки) паузу не замечают.
//
// Сценарии: «Поверх» выкл → музыка продолжает с текущего места; выкл во
// время озвучки → то же; сессия на паузе → остаётся на паузе; песня
// закончилась → ничего не дёргается.


// 🐛 ФИКС №2: «СЛУЧАЙНЫЙ ПО ПЛЕЙЛИСТАМ» ПРАКТИЧЕСКИ НЕ РАБОТАЛ
// ================================================
// Симптом: включаю случайный режим по плейлистам — очень много песен играет
// из той папки, где включил режим; пока всё не отыграет, на следующую папку
// не переходит; потом через пару песен запрыгивает опять в первую папку.
//
// Причина (player_screen.dart):
//   • В allPlaylists шаффл НЕ участвовал в выборе песни вообще: внутри папки
//     песни шли строго по порядку (list[currentIndex + 1]) до её исчертия.
//   • Случайной была только СЛЕДУЮЩАЯ папка (_switchToNextPlaylist), и в неё
//     всегда входили с ПЕРВОЙ песни.
//   • Текущая папка идентифицировалась по первой песне активного списка, а
//     системный плейлист «все песни» содержит всё и сортируется первым по
//     createdAt → идентификация сбивалась на all_songs, порядок выбора папок
//     ломался («запрыгивало в первую папку»).
//
// Исправление (player_screen.dart):
//   • Новая ветка в _playNextSong: allPlaylists + shuffle →
//     _playNextFromShuffledLibrary(); без шаффла — прежнее последовательное
//     поведение (папка за папкой, семантика режима не меняется).
//   • _playNextFromShuffledLibrary: строит глобальную перемешанную очередь из
//     ВСЕХ песен библиотеки (getAllPlaylists → песни всех плейлистов,
//     ДЕДУП по song.id — песня живёт и в папке, и в системных «все песни»/
//     «избранное», без дедупа играла бы по 2+ раза за цикл); убирает только
//     что игравшую песню (без мгновенного повтора); Fisher-Yates.
//   • Активным списком становится сама очередь (_activePlaybackList =
//     library + setCurrentPlaylist) — _playSong находит корректные индексы,
//     prev/уведомление/фоновая очередь остаются консистентными.
//   • Очередь пересобирается после исчерпания цикла (новый случайный
//     порядок); при выключении шаффла (кнопка или уведомление,
//     _onAudioServiceChanged) — сбрасывается.
//   • Study mode и watchdog'и идут через тот же _playNextSong — без
//     изменений.


