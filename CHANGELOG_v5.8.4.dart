// 🐛 ФИКС №1: КОРРЕКТОР ПОЗИЦИИ «ЗАВИСАЛ» С ПОСТОЯННЫМ ОПЕРЕЖЕНИЕМ
// ================================================
// Симптом: пользователь заново расставил метки по тапам, а подсветка
// стала переключаться раньше меток — на одну и ту же величину всю песню,
// независимо от формата файла.
//
// Корневая причина (AudioPositionCorrector, v5.6.3):
//   • Разовый «затык» доставки событий ~550–600 мс (джанк UI-изолирута,
//     GC-пауза, TTS-хэндофф аудиосессии) заводит корректор в ветку
//     wall-clock с лидом interpolated − raw ≈ 500–550 мс.
//   • Ветка «seek назад» чистит только лид > 500 мс + прирост сырой
//     позиции за тик (≈550) — НА ГРАНИЦЕ неравенство строгое, и лид,
//     «прилипший» к полосе 500–550 мс, живёт ВЕСЬ ОСТАЛЬНОЙ ПЕСНЮ.
//   • Итог: подсветка бежит на ~0.4 с впереди сырой позиции (минус
//     lyricsPositionOffset 0.15 с) → строки переключаются раньше меток
//     и слышимого звука. Постоянный сдвиг — как раз симптом.
//
// Исправление (audio_position_corrector.dart):
//   • Окно наблюдения за стабильностью лида: якорь (лид + wall-clock)
//     ставится при входе в ветку wall-clock; если за 10 с лид вырос
//     меньше 100 мс (т.е. ПОСТОЯННЫЙ, не растёт) — сырые часы
//     самосогласованы, опережение артефактно → пересинхронизация вниз
//     на raw. Настоящий VBR-дрейф отличается РАСТУЩИМ лидом (≥ ~1 с/мин
//     даёт ~167 мс роста за окно) — он как раньше корректируется
//     wall-clock и не залечивается.
//   • Инжектируемый clock (параметр конструктора, по умолчанию
//     DateTime.now) — класс стал unit-тестируемым.
//   • Прочие ветки (seek назад/вперёд, пауза/buffering, pause→play,
//     скорость) не изменены.
//
// Этим же фиксом лечатся СТАРЫЕ метки: перекладывать ничего не нужно —
// как только фантомный лид залечивается, подсветка возвращается к сырой
// позиции, по которой метки и ставились.


